#!/usr/bin/env python3
"""Generate the private CUDA Yee cell arithmetic directly from the Python trace.

The generated helper has no schedule or storage policy. Read callbacks receive
(fieldID, relative_version, dz,dy,dx), IDs Hx/Hy/Hz/Ex/Ey/Ez=0..5. Coefficients
receive (kind, component), kind decay/source=0/1. Phase is H/E=0/1. This isolates
semantic tracing from native rolling, packed-material and boundary decisions.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

try:
    from scripts.cuda_stencil_trace import emit_cuda, serialize_updates, trace_yee_step
except ModuleNotFoundError:
    from cuda_stencil_trace import emit_cuda, serialize_updates, trace_yee_step

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "cuda/src/yee_cell_generated.cuh"


def generate_header():
    updates = trace_yee_step()
    graph = json.dumps(
        serialize_updates(updates), sort_keys=True, separators=(",", ":")
    )
    digest = hashlib.sha256(graph.encode()).hexdigest()
    fields = {
        kind + c: j * 3 + i for j, kind in enumerate("HE") for i, c in enumerate("xyz")
    }

    def read_name(read):
        z, y, x = read.offset
        return f"read({fields[read.field]}, {read.version}, {z}, {y}, {x})"

    def parameter_name(name):
        if name == "inv_spacing":
            return name
        kind, field = name.split("_", 1)
        return f"coefficient({0 if kind == 'decay' else 1}, {'xyz'.index(field[1])})"

    lines = [
        "// Generated by scripts/generate_cuda_yee_cell.py; do not edit by hand.",
        f"// Semantic cell DAG SHA-256: {digest}",
        "// Versions: old H/E = 0; updated H consumed by E = 1.",
        "// Field IDs: Hx,Hy,Hz,Ex,Ey,Ez = 0,1,2,3,4,5.",
        "// This helper supplies arithmetic only; the caller proves scheduling/layout.",
        "#ifndef BEAMZ_CUDA_YEE_CELL_GENERATED_CUH_",
        "#define BEAMZ_CUDA_YEE_CELL_GENERATED_CUH_",
        "",
        "namespace beamz::cuda::generated {",
        "template <int Phase, int Component, typename ReadField, typename ReadCoefficient>",
        "__device__ __forceinline__ float AdvanceYeeCell(",
        "    float inv_spacing, ReadField read, ReadCoefficient coefficient) {",
        '  static_assert(Phase == 0 || Phase == 1, "Yee phase must be H=0 or E=1");',
        '  static_assert(Component >= 0 && Component < 3, "Yee component must be x/y/z=0/1/2");',
    ]
    for phase in range(2):
        lines.append("  if constexpr (Phase == 0) {" if phase == 0 else "  } else {")
        for component in range(3):
            branch = (
                "if constexpr (Component == 0)"
                if component == 0
                else "else if constexpr (Component == 1)"
                if component == 1
                else "else"
            )
            lines.append(f"    {branch} {{")
            value = emit_cuda(
                updates[phase * 3 + component].value,
                read_name=read_name,
                parameter_name=parameter_name,
            )
            lines.append(f"      return {value};")
            lines.append("    }")
    lines += [
        "  }",
        "}",
        "}  // namespace beamz::cuda::generated",
        "",
        "#endif  // BEAMZ_CUDA_YEE_CELL_GENERATED_CUH_",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if the checked-in header differs from current tracing",
    )
    args = parser.parse_args()
    source = generate_header()
    if args.check:
        if not args.output.exists() or args.output.read_text() != source:
            print(
                f"Generated CUDA cell header is stale: {args.output}", file=sys.stderr
            )
            return 1
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(source)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
